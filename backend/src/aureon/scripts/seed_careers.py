async def seed() -> None:
    client = get_supabase_client()

    careers = [Career.model_validate(c) for c in CAREERS]
    stories = [CareerStory.model_validate(s) for s in STORIES]

    def _upsert() -> None:
        client.table("careers").upsert(
            [c.model_dump(mode="json") for c in careers]
        ).execute()
        client.table("career_stories").upsert(
            [s.model_dump(mode="json") for s in stories]
        ).execute()

    await asyncio.to_thread(_upsert)
    print(f"Seeded {len(careers)} careers and {len(stories)} human stories.")


if __name__ == "__main__":
    asyncio.run(seed())
